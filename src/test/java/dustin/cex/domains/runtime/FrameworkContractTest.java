package dustin.cex.domains.runtime;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import java.math.BigDecimal;
import java.time.*;
import java.util.*;
import org.junit.jupiter.api.*;
import org.springframework.context.annotation.*;
import org.springframework.resilience.annotation.EnableResilientMethods;
import tools.jackson.databind.json.JsonMapper;
import dustin.cex.domains.settlement.trade.scheduler.TradeSettlementScheduler;
import dustin.cex.domains.settlement.trade.service.*;
import dustin.cex.domains.settlement.trade.service.TradeSnapshotOrchestrator;

/** 런타임 교체가 JSON 금액·시간과 실제 재시도 프록시의 실패 계약을 바꾸지 않는지 검사한다. */
class FrameworkContractTest {
    record FinancialJson(BigDecimal amount,Instant timestamp) {}
    @Test void jacksonThreePreservesExactAmountAndIsoTime() throws Exception {
        var mapper=JsonMapper.builder().build();
        var original=new FinancialJson(new BigDecimal("79228162514264337593.543950335"),Instant.parse("2026-10-22T00:00:00Z"));
        var encoded=mapper.writeValueAsString(original);var decoded=mapper.readValue(encoded,FinancialJson.class);
        assertEquals(original,decoded);assertTrue(encoded.contains("2026-10-22T00:00:00Z"));
        assertTrue(encoded.contains("79228162514264337593.543950335"));
    }
    @Test void checkConstraintStillWorksAfterSchemaConnectionCloses() throws Exception {
        String url="jdbc:h2:mem:constraint_"+UUID.randomUUID()+";DB_CLOSE_DELAY=-1";
        try {
            try(var connection=java.sql.DriverManager.getConnection(url);var sql=connection.createStatement()) {
                sql.execute("CREATE TABLE orders(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,status varchar CHECK(status IN ('pending','filled')))");
            }
            try(var connection=java.sql.DriverManager.getConnection(url);var sql=connection.createStatement()) {
                assertEquals(1,sql.executeUpdate("INSERT INTO orders(status,id) VALUES('pending',DEFAULT)"));
                assertThrows(java.sql.SQLException.class,()->sql.executeUpdate("INSERT INTO orders(status,id) VALUES('unknown',DEFAULT)"));
            }
        } finally {
            try(var connection=java.sql.DriverManager.getConnection(url);var sql=connection.createStatement()) {sql.execute("SHUTDOWN");}
        }
    }
    @Test void applicationUsesSupportedBootAndSecurityWithoutOldMapperModule() {
        assertTrue(org.springframework.boot.SpringBootVersion.getVersion().startsWith("4.1."));
        assertTrue(org.springframework.security.core.SpringSecurityCoreVersion.getVersion().startsWith("7.1."));
        assertThrows(ClassNotFoundException.class,()->Class.forName("org.springframework.boot.jackson2.autoconfigure.Jackson2AutoConfiguration"));
        assertThrows(ClassNotFoundException.class,()->Class.forName("org.springframework.retry.annotation.EnableRetry"));
    }
    @org.springframework.boot.test.context.TestConfiguration(proxyBeanMethods=false) @EnableResilientMethods
    static class Config {
        @Bean TradeSnapshotOrchestrator snapshots() {return mock(TradeSnapshotOrchestrator.class);}
        @Bean TradeSettlementService settlements() {return mock(TradeSettlementService.class);}
        @Bean TradeSettlementValidator validator() {return mock(TradeSettlementValidator.class);}
        @Bean TradeSettlementRunService runs() {return mock(TradeSettlementRunService.class);}
        @Bean TradeSettlementScheduler scheduler(TradeSnapshotOrchestrator snapshots,TradeSettlementService settlements,
                TradeSettlementValidator validator,TradeSettlementRunService runs) {
            return new TradeSettlementScheduler(snapshots,settlements,validator,runs);
        }
    }
    @Test @Timeout(20) void dailyRetryMakesThreeAttemptsAndPropagatesLastFailure() {
        try(var context=new AnnotationConfigApplicationContext(Config.class)) {
            var runs=context.getBean(TradeSettlementRunService.class);var failure=new IllegalStateException("격리 일별 정산 장애");
            when(runs.startRun(any())).thenThrow(failure);
            assertSame(failure,assertThrows(IllegalStateException.class,context.getBean(TradeSettlementScheduler.class)::createDailySettlement));
            verify(runs,times(3)).startRun(any());
        }
    }
    @Test @Timeout(20) void monthlyAggregateFailureIsNotReportedAsSuccess() {
        try(var context=new AnnotationConfigApplicationContext(Config.class)) {
            var service=context.getBean(TradeSettlementService.class);var failure=new IllegalStateException("격리 월별 정산 장애");
            when(service.createMonthlySettlement(anyInt(),anyInt())).thenThrow(failure);
            assertSame(failure,assertThrows(IllegalStateException.class,context.getBean(TradeSettlementScheduler.class)::createMonthlySettlement));
            verify(service,times(3)).createMonthlySettlement(anyInt(),anyInt());
        }
    }
    @Test @Timeout(15) void monthlyRetryStopsAfterTransientFailureSucceeds() {
        try(var context=new AnnotationConfigApplicationContext(Config.class)) {
            var service=context.getBean(TradeSettlementService.class);
            var settlement=mock(dustin.cex.domains.settlement.trade.model.entity.TradeSettlement.class);
            when(settlement.getId()).thenReturn(1L);
            when(service.createMonthlySettlement(anyInt(),anyInt())).thenThrow(new IllegalStateException("일시 장애")).thenReturn(settlement);
            when(service.getUserIdsFromTrades(any())).thenReturn(List.of());
            assertDoesNotThrow(context.getBean(TradeSettlementScheduler.class)::createMonthlySettlement);
            verify(service,times(2)).createMonthlySettlement(anyInt(),anyInt());
        }
    }
    @Test @Timeout(20) void monthlyUserFailureDoesNotBecomeSuccessfulCompletion() {
        try(var context=new AnnotationConfigApplicationContext(Config.class)) {
            var service=context.getBean(TradeSettlementService.class);
            var settlement=mock(dustin.cex.domains.settlement.trade.model.entity.TradeSettlement.class);
            when(settlement.getId()).thenReturn(1L);when(service.createMonthlySettlement(anyInt(),anyInt())).thenReturn(settlement);
            when(service.getUserIdsFromTrades(any())).thenReturn(List.of(1L));
            doThrow(new IllegalStateException("격리 사용자 정산 장애")).when(service).createUserMonthlySettlement(anyLong(),anyInt(),anyInt());
            assertThrows(IllegalStateException.class,context.getBean(TradeSettlementScheduler.class)::createMonthlySettlement);
            verify(service,times(3)).createUserMonthlySettlement(anyLong(),anyInt(),anyInt());
        }
    }
}
